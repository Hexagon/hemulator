#[derive(Error, Debug)]
pub enum N64Error {
    #[error("Invalid ROM format: {0}")]
    InvalidRom(String),
    #[error("No cartridge mounted")]
    NoCartridge,
    #[error("Invalid mount point: {0}")]
    InvalidMountPoint(String),
}

/// Debug information for N64 system
///
/// Provides runtime information about the loaded ROM and system state
/// for display in debug overlays.
#[derive(Debug, Clone)]
pub struct DebugInfo {
    /// ROM name from cartridge header (20 bytes)
    pub rom_name: String,
    /// ROM size in megabytes
    pub rom_size_mb: f32,
    /// Current PC (program counter)
    pub pc: u64,
    /// RSP microcode type
    pub rsp_microcode: String,
    /// Number of vertices in RSP vertex buffer
    pub rsp_vertex_count: usize,
    /// RDP status flags
    pub rdp_status: u32,
    /// Frame buffer resolution
    pub framebuffer_resolution: String,
    /// CPU cycle count
    pub cpu_cycles: u64,
    /// Current frame cycles
    pub frame_cycles: u32,
}

/// N64 system implementation
pub struct N64System {
    cpu: N64Cpu,
    frame_cycles: u32,
    current_cycles: u32,
    /// Instruction tracer for debugging
    instruction_tracer: emu_core::instruction_tracer::InstructionTracer,
    /// Breakpoint manager for debugging
    breakpoint_manager: emu_core::breakpoints::BreakpointManager,
}

