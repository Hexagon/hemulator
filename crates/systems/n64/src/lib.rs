impl N64System {
    /// Create a new N64 system with OpenGL renderer
    /// Requires a GL context for hardware-accelerated rendering
    pub fn new(gl: glow::Context) -> Result<Self, String> {
        let bus = N64Bus::new(gl)?;
        Ok(Self {
            cpu: N64Cpu::new(bus),
            // The N64 CPU runs at 93.75MHz with 60fps NTSC = 1,562,500 cycles/frame
            // Using the correct value ensures games initialize properly
            frame_cycles: 1_562_500,
            current_cycles: 0,
            instruction_tracer: emu_core::instruction_tracer::InstructionTracer::new(),
            breakpoint_manager: emu_core::breakpoints::BreakpointManager::new(),
        })
    }

    /// Create a new N64 system for testing (uses a null GL context)
    ///
    /// NOTE: Tests using this method require `#[ignore]` attribute because the null
    /// GL context will fail when GL functions are actually called.
    /// For proper headless GL testing, glutin+winit would be needed as dev-dependencies,
    /// but this adds complexity. Tests are functional for manual testing with real GL.
    pub fn new_for_test() -> Self {
        // Use null GL context - tests will fail at runtime if GL functions are called
        // Tests are marked as #[ignore] for this reason
        let gl = unsafe { glow::Context::from_loader_function(|_s| std::ptr::null()) };

        Self::new(gl).expect("Failed to create N64 system for test")
    }

    /// Update controller 1 state
    pub fn set_controller1(&mut self, state: ControllerState) {
        self.cpu.bus_mut().set_controller1(state);
    }

    /// Update controller 2 state
    pub fn set_controller2(&mut self, state: ControllerState) {
        self.cpu.bus_mut().set_controller2(state);
    }

    /// Update controller 3 state
    pub fn set_controller3(&mut self, state: ControllerState) {
        self.cpu.bus_mut().set_controller3(state);
    }

    /// Update controller 4 state
    pub fn set_controller4(&mut self, state: ControllerState) {
        self.cpu.bus_mut().set_controller4(state);
    }

    /// Get audio samples from the AI (Audio Interface)
    /// Returns stereo 16-bit PCM samples at the configured sample rate
    ///
    /// # Arguments
    /// * `count` - Number of stereo samples to retrieve
    ///
    /// # Notes
    /// - N64 audio is generated by the game and transferred to AI via DMA
    /// - Sample rate is configured via AI_DACRATE register (typically 44.1kHz)
    /// - Returns silence if buffer is empty
    pub fn get_audio_samples(&mut self, count: usize) -> Vec<i16> {
        self.cpu.bus_mut().ai_mut().get_audio_samples(count)
    }

    /// Get the name of the current renderer backend
    pub fn renderer_name(&self) -> &str {
        self.cpu.bus().rdp().renderer_name()
    }

    /// Get debug information for the GUI overlay
    pub fn get_debug_info(&self) -> DebugInfo {
        let bus = self.cpu.bus();

        // Get ROM name from cartridge header (if available)
        let rom_name = if let Some(cart) = bus.cartridge() {
            // N64 ROM header has game name at offset 0x20 (32 bytes into ROM)
            let name_bytes = cart.read_range(0x20, 20);
            String::from_utf8_lossy(&name_bytes)
                .trim_end_matches('\0')
                .trim()
                .to_string()
        } else {
            "No ROM".to_string()
        };

        // Get ROM size
        let rom_size_mb = if let Some(cart) = bus.cartridge() {
            cart.size() as f32 / (1024.0 * 1024.0)
        } else {
            0.0
        };

        // Get RSP microcode type
        let rsp_microcode = match bus.rsp().microcode_type() {
            rsp_hle::MicrocodeType::F3DEX => "F3DEX".to_string(),
            rsp_hle::MicrocodeType::F3DEX2 => "F3DEX2".to_string(),
            rsp_hle::MicrocodeType::Audio => "Audio".to_string(),
            rsp_hle::MicrocodeType::Unknown => "Unknown".to_string(),
        };

        // Get RSP vertex count
        let rsp_vertex_count = bus.rsp().vertex_count();

        // Get RDP status
        let rdp_status = bus.rdp().read_register(0x0C); // DPC_STATUS register

        // Get framebuffer resolution
        let frame = bus.rdp().get_frame();
        let framebuffer_resolution = format!("{}x{}", frame.width, frame.height);

        DebugInfo {
            rom_name,
            rom_size_mb,
            pc: self.cpu.cpu.pc,
            rsp_microcode,
            rsp_vertex_count,
            rdp_status,
            framebuffer_resolution,
            cpu_cycles: self.cpu.cpu.cycles,
            frame_cycles: self.current_cycles,
        }
    }

    emu_core::impl_instruction_tracer_methods!();

    /// Check if instruction tracing is enabled
    pub fn is_instruction_tracing_enabled(&self) -> bool {
        self.instruction_tracer.is_enabled()
    }

    emu_core::impl_breakpoint_methods!();

    /// Enable or disable breakpoints
    pub fn set_breakpoints_enabled(&mut self, enabled: bool) {
        self.breakpoint_manager.set_enabled(enabled);
    }

    /// Get the breakpoint manager
    pub fn get_breakpoint_manager(&self) -> &emu_core::breakpoints::BreakpointManager {
        &self.breakpoint_manager
    }

    /// Check if the current PC is at an execute breakpoint.
    /// Returns `Some(pc)` if a breakpoint is hit, `None` otherwise.
    pub fn check_breakpoint(&self) -> Option<u32> {
        let pc = self.cpu.cpu.pc as u32;
        if self.breakpoint_manager.should_break_execute(pc) {
            Some(pc)
        } else {
            None
        }
    }

    /// Get debugger interface for this system
    pub fn debugger(&self) -> Option<&dyn emu_core::debug::Debugger> {
        Some(self)
    }

    /// Get the current frame_cycles setting
    pub fn get_frame_cycles(&self) -> u32 {
        self.frame_cycles
    }

    /// Set the frame_cycles for performance tuning
    ///
    /// # Arguments
    /// * `cycles` - Number of CPU cycles to execute per frame (recommended: 50,000 - 200,000)
    ///
    /// # Notes
    /// - Lower values: Better performance, less accurate timing
    /// - Higher values: Worse performance, more accurate timing
    /// - Hardware accurate: 1,562,500 cycles/frame (93.75MHz / 60Hz)
    /// - Default: 50,000 cycles/frame for good performance
    pub fn set_frame_cycles(&mut self, cycles: u32) {
        self.frame_cycles = cycles;
        log(LogCategory::CPU, LogLevel::Info, || {
            format!(
                "N64: Frame cycles set to {} (~{:.2} MHz effective at 60fps)",
                cycles,
                (cycles as f64 * 60.0) / 1_000_000.0
            )
        });
    }

    /// Export the cartridge save data (SRAM, EEPROM, or FlashRAM) for persistence.
    ///
    /// Returns `None` when no save storage is configured for the loaded cartridge.
    /// The format matches what [`Self::set_save_data`] expects, making round-trips
    /// lossless:
    ///
    /// ```no_run
    /// # use emu_n64::N64System;
    /// # fn f(sys: &mut N64System, saved: Vec<u8>) {
    /// // Save
    /// if let Some(data) = sys.get_save_data() {
    ///     std::fs::write("save.bin", &data).ok();
    /// }
    /// // Load
    /// if let Ok(data) = std::fs::read("save.bin") {
    ///     sys.set_save_data(data).ok();
    /// }
    /// # }
    /// ```
    pub fn get_save_data(&self) -> Option<Vec<u8>> {
        self.cpu.bus().get_save_data()
    }

    /// Import previously persisted save data.
    ///
    /// Returns `Err` if the data length does not match the configured save storage,
    /// if no save storage is configured for the current cartridge, or if another
    /// underlying error occurs.
    pub fn set_save_data(&mut self, data: Vec<u8>) -> Result<(), String> {
        self.cpu.bus_mut().set_save_data(data)
    }

    /// Export controller pak (mempak) data for the given controller slot (0-based).
    ///
    /// Returns `None` when no pak is currently inserted in that slot.
    pub fn get_mempak_data(&self, channel: usize) -> Option<Vec<u8>> {
        self.cpu.bus().get_mempak_data(channel)
    }

    /// Import previously persisted controller pak data for a controller slot.
    pub fn set_mempak_data(&mut self, channel: usize, data: Vec<u8>) -> Result<(), String> {
        self.cpu.bus_mut().set_mempak_data(channel, data)
    }

    /// Enable or disable the controller pak in a given controller slot.
    ///
    /// Slot 0 (controller 1) is enabled by default.
    pub fn set_mempak_enabled(&mut self, channel: usize, enabled: bool) {
        self.cpu.bus_mut().set_mempak_enabled(channel, enabled);
    }
}

impl System for N64System {
    type Error = N64Error;

    fn reset(&mut self) {
        self.cpu.reset();
        self.cpu.bus_mut().rdp_mut().reset();
        self.current_cycles = 0;
    }

    fn step_frame(&mut self) -> Result<Frame, Self::Error> {
        self.current_cycles = 0;

        // Log every 60th frame (once per second at 60fps)
        static mut FRAME_COUNTER: u32 = 0;
        unsafe {
            FRAME_COUNTER += 1;
            if FRAME_COUNTER.is_multiple_of(60) {
                let counter = FRAME_COUNTER; // Copy to avoid shared reference
                log(LogCategory::PPU, LogLevel::Info, || {
                    format!("N64: Frame {} complete", counter)
                });
            }
        }

        // NTSC has 262 scanlines per frame
        const SCANLINES_PER_FRAME: u32 = 262;
        let cycles_per_scanline = self.frame_cycles / SCANLINES_PER_FRAME;

        // Execute CPU cycles for one frame, updating VI scanline
        for scanline in 0..SCANLINES_PER_FRAME {
            let target_cycles = (scanline + 1) * cycles_per_scanline;

            // Execute CPU until we reach the cycles for this scanline
            while self.current_cycles < target_cycles {
                // Capture PC before execution for tracing
                let pc_before = self.cpu.cpu.pc as u32;

                let cycles = self.cpu.step();
                self.current_cycles += cycles;

                // Record instruction in tracer if enabled
                if self.instruction_tracer.is_enabled() {
                    if let Some(instruction) = self.disassemble_instruction(pc_before) {
                        let cpu_state = self.get_cpu_state();
                        self.instruction_tracer.trace(instruction, cpu_state);
                    }
                }
            }

            // Check for pending interrupts once per scanline (performance optimization)
            // This is much faster than checking every instruction
            let bus = self.cpu.bus();
            let pending = bus.mi().get_pending_interrupts();
            if pending != 0 {
                // On real N64, ALL MI interrupts are OR'd and routed to CPU IP2
                // (interrupt line 2). Individual MI interrupt bits are distinguished
                // by reading MI_INTR_REG, not by separate CPU interrupt lines.
                self.cpu.cpu.set_interrupt(2);
            } else {
                // Clear IP2 when no MI interrupts are pending
                self.cpu.cpu.clear_interrupt(2);
            }

            // Update VI scanline and check for interrupt
            let bus = self.cpu.bus_mut();
            if bus.vi_mut().update_scanline(scanline) {
                // VI interrupt triggered - set interrupt in MI (only if not already set)
                let mi_status = bus.mi().get_interrupt_status();
                if (mi_status & crate::mi::MI_INTR_VI) == 0 {
                    bus.mi_mut().set_interrupt(crate::mi::MI_INTR_VI);

                    log(LogCategory::Interrupts, LogLevel::Info, || {
                        format!("N64: VI interrupt triggered at scanline {}", scanline)
                    });
                }
            }
        }

        // Get frame from VI framebuffer readback (primary display method)
        // The game renders to RDRAM, and VI reads from RDRAM at VI_ORIGIN
        if let Some(vi_frame) = self.cpu.bus().read_vi_framebuffer() {
            return Ok(vi_frame);
        }

        // Fallback: return RDP internal frame (for cases where VI isn't configured yet)
        let frame = self.cpu.bus().rdp().get_frame().clone();
        Ok(frame)
    }

    fn save_state(&self) -> serde_json::Value {
        serde_json::json!({
            "version": 1,
            "cpu": {
                "gpr": self.cpu.cpu.gpr,
                "pc": self.cpu.cpu.pc,
                "hi": self.cpu.cpu.hi,
                "lo": self.cpu.cpu.lo,
                "cycles": self.cpu.cpu.cycles,
            }
        })
    }

    fn load_state(&mut self, v: &serde_json::Value) -> Result<(), serde_json::Error> {
        if let Some(cpu_state) = v.get("cpu") {
            if let Some(gpr_array) = cpu_state["gpr"].as_array() {
                for (i, val) in gpr_array.iter().enumerate() {
                    if i < 32 {
                        self.cpu.cpu.gpr[i] = val.as_u64().unwrap_or(0);
                    }
                }
            }
            self.cpu.cpu.pc = cpu_state["pc"].as_u64().unwrap_or(0);
            self.cpu.cpu.hi = cpu_state["hi"].as_u64().unwrap_or(0);
            self.cpu.cpu.lo = cpu_state["lo"].as_u64().unwrap_or(0);
            self.cpu.cpu.cycles = cpu_state["cycles"].as_u64().unwrap_or(0);
        }
        Ok(())
    }

    fn supports_save_states(&self) -> bool {
        true
    }

    fn mount_points(&self) -> Vec<MountPointInfo> {
        vec![MountPointInfo {
            id: "Cartridge".to_string(),
            name: "Cartridge Slot".to_string(),
            extensions: vec!["z64".to_string(), "n64".to_string(), "v64".to_string()],
            required: true,
        }]
    }

    fn mount(&mut self, mount_point_id: &str, data: &[u8]) -> Result<(), Self::Error> {
        if mount_point_id != "Cartridge" {
            return Err(N64Error::InvalidMountPoint(mount_point_id.to_string()));
        }

        self.cpu.bus_mut().load_cartridge(data)?;
        self.reset();
        Ok(())
    }

    fn unmount(&mut self, mount_point_id: &str) -> Result<(), Self::Error> {
        if mount_point_id != "Cartridge" {
            return Err(N64Error::InvalidMountPoint(mount_point_id.to_string()));
        }

        self.cpu.bus_mut().unload_cartridge();
        Ok(())
    }

    fn is_mounted(&self, mount_point_id: &str) -> bool {
        mount_point_id == "Cartridge" && self.cpu.bus().has_cartridge()
    }
}

